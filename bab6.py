# Bab 6: Lists dan Dictionaries

# Contoh List
buah = ["Apel", "Mangga", "Jeruk"]

print("Daftar Buah:")
for item in buah:
    print(item)

# Contoh Dictionary
siswa = {
    "nama": "Eva",
    "kelas": 11,
    "jurusan": "RPL"
}

print("\nData Siswa:")
print("Nama:", siswa["nama"])
print("Kelas:", siswa["kelas"])
print("Jurusan:", siswa["jurusan"])
